// 一袋台词抽完前不重复；洗牌发生在新一袋开始时。
export function makeLinePicker(lines: readonly string[], rng: () => number = () => 0.5) {
  let bag: string[] = [];
  return () => {
    if (!lines.length) return '';
    if (!bag.length) {
      // 重新洗牌（Fisher-Yates）
      bag = lines.slice();
      for (let i = bag.length - 1; i > 0; i--) {
        const j = Math.floor(rng() * (i + 1));
        [bag[i], bag[j]] = [bag[j], bag[i]];
      }
    }
    return bag.pop() ?? '';
  };
}
